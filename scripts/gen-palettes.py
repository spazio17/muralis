#!/usr/bin/env python3
"""Generates Muralis's colour scheme (2026-10-15: ultramarine, the painters' blue of
Italian frescoes, one scheme for everyone, dark and light), with Google's own
material-color-utilities (HCT), so it is Material 3 as specified. Writes
app/src/main/java/org/spazio17/muralis/Palettes.java and app/src/main/res/raw/admin_palettes.css;
both are committed, so the build needs neither Python nor the library.
    python3 -m pip install --user --no-deps material-color-utilities-python
"""
import os
from material_color_utilities_python import TonalPalette, argbFromHex, hexFromArgb
from material_color_utilities_python.hct.hct import Hct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEED = '#1C39BB'  # ultramarine
# One recipe for the colours, Material's Vibrant (the chroma pushed as far as the screen allows,
# the neutrals tinted a little), at Material's standard tones. The second choice went twice on
# 2026-10-04: Material's variants told apart too little on a dark panel, and its contrast levels
# did not look good; other apps offer a colour and day or night, nothing more.
CHROMA = dict(p=200, s=24, n=10, nv=12)
TONES = dict(surface=(6, 98), lowest=(4, 100), high=(17, 92), highest=(22, 90), outline=(60, 50),
             onSurface=(90, 10), onSurfaceVariant=(80, 30), primary=(80, 40), onPrimary=(20, 100),
             secondary=(80, 40), onSecondaryContainer=(90, 10), error=(80, 40))
# The status colours are not a scheme's business: green and yellow mean the same in every one.
OK = {'dark': '#8ee88a', 'light': '#227212'}
WARN = {'dark': '#ffdf8f', 'light': '#905600'}
ERROR = TonalPalette.fromHueAndChroma(25, 84)

def hx(p, tone): return hexFromArgb(p.tone(tone))

def palettes(seed):
    hue = Hct.fromInt(argbFromHex(seed)).hue
    return (TonalPalette.fromHueAndChroma(hue, CHROMA['p']), TonalPalette.fromHueAndChroma(hue, CHROMA['s']),
            TonalPalette.fromHueAndChroma(hue, CHROMA['n']), TonalPalette.fromHueAndChroma(hue, CHROMA['nv']))

def scheme(seed, dark):
    p, s, n, nv = palettes(seed)
    t = {k: v[0 if dark else 1] for k, v in TONES.items()}
    # KioskTheme's thirteen, in its constructor's order: base, mantle, surface, surfaceAlt, border,
    # text, subtext, accent, accentAlt, ok, warn, bad, inkAlt; then on-primary and the lowest
    # surface, which both surfaces used to hardcode (review, 2026-10-04).
    return [hx(n, t['surface']), hx(n, t['lowest']), hx(n, t['high']), hx(n, t['highest']), hx(nv, t['outline']),
            hx(n, t['onSurface']), hx(nv, t['onSurfaceVariant']), hx(p, t['primary']), hx(s, t['secondary']),
            OK['dark' if dark else 'light'], WARN['dark' if dark else 'light'], hx(ERROR, t['error']),
            hx(s, t['onSecondaryContainer']), hx(p, t['onPrimary']), hx(n, t['lowest'])]

CSS_NAMES = ['base', 'mantle', 'surface', 'surface-alt', 'border', 'text', 'subtext', 'accent',
             'accent-alt', 'ok', 'warn', 'bad', 'ink-alt', 'on-accent', 'lowest']
java = ['/*', ' * Copyright 2026 Muralis contributors', ' * Fair Core License, FCL-1.0-ALv2: see LICENSE.md at the repository root.', ' */',
        'package org.spazio17.muralis;', '',
        '/**', ' * Muralis\'s colour scheme, Material 3 from the ultramarine seed, dark and light, fifteen colours:',
        ' * the thirteen of KioskTheme\'s constructor, then on-primary and surface-container-lowest.',
        ' * GENERATED by scripts/gen-palettes.py with Google\'s material-color-utilities; edit the',
        ' * script, not this file. Pure, for the host tests.', ' */',
        'final class Palettes {', '    private Palettes() {', '    }', '',
        '    /** The scheme\'s fifteen colours, dark or light. */',
        '    static String[] colours(boolean dark) {',
        '        return dark',
        '                ? new String[] {' + ', '.join(f'"{c}"' for c in scheme(SEED, True)) + '}',
        '                : new String[] {' + ', '.join(f'"{c}"' for c in scheme(SEED, False)) + '};',
        '    }', '}', '']
dark = ';'.join(f'--{n}:{c}' for n, c in zip(CSS_NAMES, scheme(SEED, True)))
light = ';'.join(f'--{n}:{c}' for n, c in zip(CSS_NAMES, scheme(SEED, False)))
css = ['/* GENERATED by scripts/gen-palettes.py: Muralis\'s colour scheme, Material 3 from the',
       '   ultramarine seed; the three theme rules mirror the stylesheet\'s own. Edit the script,',
       '   not this file. */',
       f':root{{{light}}}',
       f':root[data-theme=light]{{{light}}}',
       f'@media (prefers-color-scheme:dark){{:root:not([data-theme=light]){{{dark}}}}}',
       f':root[data-theme=dark]{{{dark}}}']
open(os.path.join(ROOT, 'app/src/main/java/org/spazio17/muralis/Palettes.java'), 'w').write('\n'.join(java))
open(os.path.join(ROOT, 'app/src/main/res/raw/admin_palettes.css'), 'w').write('\n'.join(css) + '\n')
print('Palettes.java and admin_palettes.css written')
print('ultramarine dark', scheme(SEED, True)[:9])
